УСТАНОВКА OH MY PI В TERMUX ЧЕРЕЗ PROOT-КОНТЕЙНЕР

Все команды выполняются по очереди.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
1. ПОДГОТОВКА TERMUX
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Обновить пакеты:

pkg update -y && pkg upgrade -y

Установить необходимые компоненты:

pkg install -y proot-distro git curl

Разрешить Termux доступ к памяти телефона:

termux-setup-storage

После появления системного окна нажать «Разрешить».


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
2. СОЗДАНИЕ КОНТЕЙНЕРА OMP
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Установить Ubuntu 24.04 и назвать контейнер omp:

proot-distro install ubuntu:24.04 --name omp

Если команда сообщает, что параметр --name неизвестен, используется старая версия proot-distro. Тогда выполнить:

proot-distro install ubuntu --override-alias omp


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
3. ВХОД В КОНТЕЙНЕР
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

proot-distro login omp

Все следующие команды выполняются уже внутри контейнера.


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
4. УСТАНОВКА СИСТЕМНЫХ ПАКЕТОВ
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

apt update && apt upgrade -y

apt install -y \
  curl \
  ca-certificates \
  git \
  unzip \
  build-essential \
  python3 \
  python3-pip \
  ripgrep \
  fd-find \
  nano


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
5. УСТАНОВКА BUN
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

curl -fsSL https://bun.sh/install | bash

Добавить Bun в PATH:

echo 'export BUN_INSTALL="$HOME/.bun"' >> ~/.bashrc
echo 'export PATH="$BUN_INSTALL/bin:$PATH"' >> ~/.bashrc

Применить настройки:

source ~/.bashrc

Проверить установку:

bun --version

Нужна версия Bun 1.3.14 или новее.


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
6. УСТАНОВКА OH MY PI
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

bun install -g @oh-my-pi/pi-coding-agent

Проверить установку:

omp --version


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
7. ПЕРВЫЙ ЗАПУСК
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Создать папку для проектов во внутренней памяти телефона:

mkdir -p /storage/emulated/0/AiWork

Перейти в неё:

cd /storage/emulated/0/AiWork

Запустить Oh My Pi:

omp

В интерфейсе OMP для подключения провайдера можно использовать:

/login

Для выбора модели:

/model


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
КАК ЗАПУСКАТЬ ПОТОМ
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

После закрытия Termux для повторного запуска сначала войти в контейнер:

proot-distro login omp

Затем перейти в папку проектов:

cd /storage/emulated/0/AiWork

И запустить Oh My Pi:

omp


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
КАК ВЫЙТИ
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Сначала закрыть OMP сочетанием:

Ctrl+C

Затем выйти из контейнера:

exit


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ОБНОВЛЕНИЕ OH MY PI
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Войти в контейнер:

proot-distro login omp

Обновить OMP:

bun update -g @oh-my-pi/pi-coding-agent

Проверить версию:

omp --version


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ЕСЛИ КОМАНДА OMP НЕ НАЙДЕНА
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Выполнить:

export BUN_INSTALL="$HOME/.bun"
export PATH="$BUN_INSTALL/bin:$PATH"
source ~/.bashrc

Проверить:

which omp
omp --version


━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ЕСЛИ КОНТЕЙНЕР НЕ ЗАПУСКАЕТСЯ
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Попробовать:

export PROOT_NO_SECCOMP=1
proot-distro login omp

Чтобы настройка сохранилась:

echo 'export PROOT_NO_SECCOMP=1' >> ~/.bashrc
